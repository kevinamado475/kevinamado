# pedimos dos numeros en coma flotante (float)
num1 = float(input("Introdueix el primer número: "))
num2 = float(input("Introdueix el segon número: "))
# sumamos los dos numeros y los convertimos a entero (int) o (casting)
suma = num1 + num2
resultado = int(suma)
#mostramos el resultado de orginal y el resultado de la suma convertida a entero
print("El resultat de la suma és:", suma)
print("El resultat de la suma convertida a enter és:", resultado)
