# escrive un programa lee 3 numero y diga cual es el mayor de los 3
numero1 = float(input("introduce el primer numero: "))
numero2 = float(input("introduce el segundo numero: "))
numero3 = float(input("introduce el tercer numero: "))
# evaluar cual es el mayor de los 3 numeros
el_mayor = max(numero1, numero2, numero3)
print("El mayor de los 3 numeros es:", el_mayor)
